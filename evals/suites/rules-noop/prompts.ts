// The one-turn prompts of the rules no-op suite (design D-8). M1 asks a
// question blind; M2 reviews a seeded patch with the reviewer role and its
// adapter as the system prompt, and the rule files appended only in the
// "with" cells, under the section titles `bdk ctx skill` gives them.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

import { REPO_ROOT } from "../../harness/paths.ts";
import { RULE_DIRS } from "./bullets.ts";

export const M1_SYSTEM = [
  "You answer questions about software engineering practice.",
  "Answer in at most five sentences: say what to do and why.",
].join(" ");

/** The M1 user turn is the question itself. */
export const M1_PROMPT = "{{question}}";

export const M2_PROMPT = "Review this change.\n\n```diff\n{{diff}}\n```";

/** What a reviewer does when the change arrives in the message instead of a dispatch package. */
const ONE_TURN = [
  "## This review",
  "",
  "This review runs as one turn without tools and without a dispatch package: the change is in the message.",
  "You cannot run tests, read files or write ledger entries, so report in your reply instead of the ledger.",
  "List each problem as one line `- <file>:<line> [<severity>] <problem>`, with the rule id when a rule applies.",
  "Reply `no findings` when there is none.",
].join("\n");

function body(markdown: string): string {
  const match = /^---\n[\s\S]*?\n---\n/.exec(markdown);
  const text = match === null ? markdown : markdown.slice(match[0].length);
  return text
    .split("\n")
    .filter((line) => !line.startsWith("# Generated by"))
    .join("\n")
    .trim();
}

/** Every rule file as a section titled like its `bdk ctx skill` section. */
function ruleSections(repoRoot = REPO_ROOT): string[] {
  return RULE_DIRS.flatMap((dir) =>
    readdirSync(join(repoRoot, dir))
      .filter((name) => name.endsWith(".md"))
      .sort()
      .map((name) => {
        const stem = name.slice(0, -".md".length);
        const title = dir === "rules" ? `Rules: ${stem}` : `Language rules: ${stem}`;
        return `## ${title}\n\n${readFileSync(join(repoRoot, dir, name), "utf8").trim()}`;
      }),
  );
}

/** The reviewer system prompt: adapter, role contract, the one-turn note, and the rules when `withRules`. */
export function reviewerSystem(withRules: boolean, repoRoot = REPO_ROOT): string {
  const read = (path: string): string => body(readFileSync(join(repoRoot, path), "utf8"));
  return [
    read("agents/reviewer.md"),
    read("skills/roles/reviewer/SKILL.md"),
    ONE_TURN,
    ...(withRules ? ruleSections(repoRoot) : []),
  ].join("\n\n");
}
