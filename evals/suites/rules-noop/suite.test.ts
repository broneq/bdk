import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { readVersions } from "../../harness/paths.ts";
import type { EvalItem } from "../../harness/series.ts";
import { reviewerSystem } from "./prompts.ts";
import { HAIKU, SONNET, describeMeasurement, m1Items, m2Items, probeItems } from "./suite.ts";
import type { MeasurementSpec } from "./suite.ts";

function spec(kind: "m1" | "m2", items: readonly EvalItem[]): MeasurementSpec {
  return {
    kind,
    series: `series-${kind}`,
    dir: "/tmp/series",
    items,
    bdkCommit: "b".repeat(40),
    versions: readVersions(),
    runs: 5,
    budgetUsd: 100,
    runCapUsd: 15,
    ledgerFile: "/tmp/budget.json",
    resultsFile: "/tmp/rows.jsonl",
  };
}

describe("items", () => {
  it("has one M1 item per question and one M2 item per patch, carrying its text", () => {
    const m1 = m1Items();
    expect(m1).toHaveLength(131);
    expect(m1[0]?.vars.question).not.toBe("");
    const m2 = m2Items();
    expect(m2.map((item) => item.id).at(-1)).toBe("21-clean-sync-state");
    expect(m2[0]?.vars.diff).toMatch(/^diff --git /);
  });

  it("probes items spread over the list, first and last included", () => {
    const items = ["a", "b", "c", "d", "e", "f", "g"].map((id) => ({ id, vars: {} }));
    expect(probeItems(items, 3).map((item) => item.id)).toEqual(["a", "d", "g"]);
    expect(probeItems(items.slice(0, 2), 3)).toHaveLength(2);
  });
});

describe("describeMeasurement", () => {
  it("M1: blind one-turn cells, Sonnet twice, no fixture", () => {
    const setup = describeMeasurement(spec("m1", m1Items().slice(0, 2)));
    expect(Object.keys(setup.cells)).toEqual(["haiku", "sonnet", "sonnet-prime"]);
    expect(setup.cells.haiku?.provider.config).toMatchObject({
      model: HAIKU,
      tools: [],
      max_turns: 1,
    });
    expect(setup.cells["sonnet-prime"]?.provider.config).toMatchObject({ model: SONNET });
    expect(setup.cells.sonnet?.plan).toMatchObject({
      expectedPlugins: 0,
      workDir: null,
      provenance: { fixtureCommit: null },
      settings: { measurement: "m1" },
    });
    expect(setup.prompt).toBe("{{question}}");
    // One call's cap, never the session cap.
    expect(setup.plan.runCapUsd).toBe(1);
  });

  it("M2: the rules only in the with cells, recorded in the variant hash", () => {
    const setup = describeMeasurement(spec("m2", m2Items().slice(0, 1)));
    expect(Object.keys(setup.cells)).toEqual(["with", "with-prime", "without"]);
    const system = (cell: string): unknown =>
      setup.cells[cell]?.provider.config.custom_system_prompt;
    expect(system("with")).toBe(reviewerSystem(true));
    expect(system("with-prime")).toBe(system("with"));
    expect(system("without")).toBe(reviewerSystem(false));
    const hashes = ["with", "with-prime", "without"].map(
      (cell) => setup.cells[cell]?.plan.provenance.variantHash,
    );
    expect(hashes[0]).toBe(hashes[1]);
    expect(hashes[2]).not.toBe(hashes[0]);
    expect(setup.cells.with?.plan.provenance.fixtureCommit).toBe(readVersions().fixture.commit);
    expect(setup.cells.with?.provider.config.working_dir).toBe(join("/tmp/series", "empty"));
  });
});

describe("reviewerSystem", () => {
  it("joins the adapter, the role contract and the one-turn note, without frontmatter", () => {
    const without = reviewerSystem(false);
    expect(without).toMatch(/^You are a BDK reviewer/);
    expect(without).toContain("# Role: reviewer");
    expect(without).toContain("## This review");
    expect(without).not.toContain("---\nname:");
    expect(without).not.toContain("# Generated by");
    expect(without).not.toContain("## Rules:");
  });

  it("appends every rule file under its ctx section title in the with cells", () => {
    const withRules = reviewerSystem(true);
    expect(withRules).toContain("## Rules: security");
    expect(withRules).toContain("## Language rules: typescript");
    expect(withRules.startsWith(reviewerSystem(false))).toBe(true);
  });
});
